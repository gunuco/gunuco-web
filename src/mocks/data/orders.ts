function order(
  partial: Omit<Order, 'fulfillmentMethod' | 'pickupStatus'> &
    Partial<Pick<Order, 'fulfillmentMethod' | 'pickupStatus'>>,
): Order {
  const fulfillmentMethod: FulfillmentMethod =
    partial.fulfillmentMethod ??
    (partial.source === 'pos' || partial.deliveryFee === 0 ? 'pickup_at_store' : 'doorstep_delivery');
  const pickupStatus: PickupStatus =
    partial.pickupStatus ??
    (fulfillmentMethod === 'pickup_at_store'
      ? partial.status === 'delivered'
        ? 'collected'
        : 'pickup_scheduled'
      : 'not_applicable');
  return { ...partial, fulfillmentMethod, pickupStatus };
}

